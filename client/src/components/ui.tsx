import type { ReactNode } from 'react';
import { STATUS_LABEL, STATUS_TONE } from '../format';

/** Status pill: tone + text label, so meaning never relies on colour alone. */
export function StatusBadge({ status }: { status: string }) {
  const tone = STATUS_TONE[status] ?? 'info';
  const icon = { ok: '✓', warn: '!', bad: '✕', info: '•' }[tone];
  return (
    <span className={`badge badge-${tone}`}>
      <span aria-hidden="true">{icon}</span> {STATUS_LABEL[status] ?? status}
    </span>
  );
}

export function AiBadge({ source }: { source: string }) {
  return source === 'ai' ? (
    <span className="badge badge-ai" title="Generated by Gemini">
      <span aria-hidden="true">✦</span> AI
    </span>
  ) : (
    <span className="badge badge-muted" title="Deterministic fallback">
      Rule-based
    </span>
  );
}

/** Polite live region for async results and confirmations. */
export function Notice({
  tone = 'info',
  children,
}: {
  tone?: 'info' | 'ok' | 'bad';
  children: ReactNode;
}) {
  return (
    <div className={`notice notice-${tone}`} role={tone === 'bad' ? 'alert' : 'status'}>
      {children}
    </div>
  );
}

export function Loading({ label = 'Loading' }: { label?: string }) {
  return (
    <p className="loading" role="status">
      <span className="spinner" aria-hidden="true" /> {label}…
    </p>
  );
}

export function PageHeader({ title, intro }: { title: string; intro?: string }) {
  return (
    <header className="page-header">
      <h1 tabIndex={-1} id="page-title">
        {title}
      </h1>
      {intro && <p className="muted">{intro}</p>}
    </header>
  );
}

export function errorMessage(err: unknown): string {
  return err instanceof Error ? err.message : 'Something went wrong';
}

/** Loading -> empty -> content, the standard states of an async list. */
export function DataState<T>({
  items,
  empty,
  children,
}: {
  items: T[] | null;
  empty: ReactNode;
  children: (items: T[]) => ReactNode;
}) {
  if (!items) return <Loading />;
  if (items.length === 0) return <>{empty}</>;
  return <>{children(items)}</>;
}
